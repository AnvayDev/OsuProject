// Ported from osu.Game.Rulesets.Osu/Objects/Slider.cs

import { BindableDouble } from '@fw/bindables/BindableNumber';
import type { Vector2F } from '@fw/layout/Vector2F';
import { HitSampleInfo } from '../../../audio/HitSampleInfo';
import type { IBeatmapDifficultyInfo } from '../../../beatmaps/BeatmapDifficulty';
import type { ControlPointInfo } from '../../../beatmaps/controlPoints/ControlPointInfo';
import type { Judgement } from '../../judgements/Judgement';
import { LegacyRulesetExtensions } from '../../objects/legacy/LegacyRulesetExtensions';
import { PathControlPoint } from '../../objects/PathControlPoint';
import { SliderEventGenerator, SliderEventType } from '../../objects/SliderEventGenerator';
import { SliderPath } from '../../objects/SliderPath';
import {
  curvePositionAt, getNodeSamples, populateNodeSamples, spanCount,
  type IHasGenerateTicks, type IHasPathWithRepeats, type IHasSliderVelocity,
} from '../../objects/types/Types';
import { HitWindows } from '../../scoring/HitWindows';
import { OsuIgnoreJudgement, OsuJudgement } from '../judgements/OsuJudgement';
import { OsuHitObject } from './OsuHitObject';
import { SliderHeadCircle } from './SliderHeadCircle';
import { SliderRepeat } from './SliderRepeat';
import { SliderTailCircle } from './SliderTailCircle';
import { SliderTick } from './SliderTick';

export class Slider extends OsuHitObject implements IHasPathWithRepeats, IHasSliderVelocity, IHasGenerateTicks {
  get endTime(): number {
    return this.startTime + spanCount(this) * this.path.distance / this.velocity;
  }

  get duration(): number {
    return this.endTime - this.startTime;
  }

  override get auxiliarySamples(): readonly HitSampleInfo[] {
    return [...this.createSlidingSamples(), ...this.tailSamples];
  }

  private endPositionCache: Vector2F | null = null;

  override get endPosition(): Vector2F {
    return this.endPositionCache ??= this.position.add(curvePositionAt(this, 1));
  }

  stackedPositionAt(t: number): Vector2F {
    return this.stackedPosition.add(curvePositionAt(this, t));
  }

  private readonly pathBacking = new SliderPath();

  get path(): SliderPath {
    return this.pathBacking;
  }

  set path(value: SliderPath) {
    this.pathBacking.controlPoints.clear();
    this.pathBacking.controlPoints.addRange(value.controlPoints.toArray().map(c => new PathControlPoint(c.position, c.type)));
    this.pathBacking.expectedDistance.value = value.expectedDistance.value;
  }

  get distance(): number {
    return this.path.distance;
  }

  override get position(): Vector2F {
    return super.position;
  }

  override set position(value: Vector2F) {
    super.position = value;
    this.updateNestedPositions();
  }

  nodeSamples: HitSampleInfo[][] = [];

  tailSamples: readonly HitSampleInfo[] = [];

  private repeatCountBacking = 0;

  /** The amount of times the slider repeats. */
  get repeatCount(): number {
    return this.repeatCountBacking;
  }

  set repeatCount(value: number) {
    this.repeatCountBacking = value;
    this.updateNestedPositions();
  }

  /** The length of one span of this Slider. */
  get spanDuration(): number {
    return this.duration / spanCount(this);
  }

  /** Velocity of this Slider. */
  velocity = 0;

  /** Spacing between SliderTicks of this Slider. */
  tickDistance = 0;

  /** An extra multiplier that affects the number of SliderTicks generated by this Slider. An increase in this value increases tickDistance, which reduces the number of ticks generated. */
  tickDistanceMultiplier = 1;

  private classicSliderBehaviourBacking = false;

  /**
   * If false, the slider's judgement is ignored: the head is a full hit circle, and the tail provides the final combo.
   * If true, the slider is judged as a whole, as in osu!stable (the Classic mod).
   */
  get classicSliderBehaviour(): boolean {
    return this.classicSliderBehaviourBacking;
  }

  set classicSliderBehaviour(value: boolean) {
    this.classicSliderBehaviourBacking = value;

    if (this.headCircle !== null)
      this.headCircle.classicSliderBehaviour = value;
    if (this.tailCircle !== null)
      this.tailCircle.classicSliderBehaviour = value;
  }

  readonly sliderVelocityMultiplierBindable = new BindableDouble(1).with({ minValue: 0.1, maxValue: 10 });

  get sliderVelocityMultiplier(): number {
    return this.sliderVelocityMultiplierBindable.value;
  }

  set sliderVelocityMultiplier(value: number) {
    this.sliderVelocityMultiplierBindable.value = value;
  }

  generateTicks = true;

  headCircle: SliderHeadCircle | null = null;

  tailCircle: SliderTailCircle | null = null;

  lastRepeat: SliderRepeat | null = null;

  constructor() {
    super();

    this.pathBacking.optimiseCatmull = true;

    this.samplesBindable.collectionChanged.add(() => this.updateNestedSamples());
    this.path.version.valueChanged.add(() => this.updateNestedPositions());
  }

  protected override applyDefaultsToSelf(controlPointInfo: ControlPointInfo, difficulty: IBeatmapDifficultyInfo): void {
    super.applyDefaultsToSelf(controlPointInfo, difficulty);

    const timingPoint = controlPointInfo.timingPointAt(this.startTime);

    this.velocity = OsuHitObject.BASE_SCORING_DISTANCE * difficulty.sliderMultiplier / LegacyRulesetExtensions.getPrecisionAdjustedBeatLength(this, timingPoint, 'osu');

    // WARNING: this is intentionally not computed as `BASE_SCORING_DISTANCE * difficulty.SliderMultiplier`
    // for backwards compatibility reasons (intentionally introducing floating point errors to match stable).
    const scoringDistance = this.velocity * timingPoint.beatLength;

    this.tickDistance = this.generateTicks ? (scoringDistance / difficulty.sliderTickRate * this.tickDistanceMultiplier) : Infinity;
  }

  protected override createNestedHitObjects(): void {
    super.createNestedHitObjects();

    const sliderEvents = SliderEventGenerator.generate(this.startTime, this.spanDuration, this.velocity, this.tickDistance, this.path.distance, spanCount(this));

    for (const e of sliderEvents) {
      switch (e.type) {
        case SliderEventType.Tick: {
          const tick = new SliderTick();
          tick.spanIndex = e.spanIndex;
          tick.spanStartTime = e.spanStartTime;
          tick.startTime = e.time;
          tick.position = this.position.add(this.path.positionAt(e.pathProgress));
          tick.pathProgress = e.pathProgress;
          tick.stackHeight = this.stackHeight;
          this.addNested(tick);
          break;
        }

        case SliderEventType.Head: {
          const head = this.headCircle = new SliderHeadCircle();
          head.startTime = e.time;
          head.position = this.position;
          head.stackHeight = this.stackHeight;
          head.classicSliderBehaviour = this.classicSliderBehaviour;
          this.addNested(head);
          break;
        }

        case SliderEventType.Tail: {
          const tail = this.tailCircle = new SliderTailCircle(this);
          tail.repeatIndex = e.spanIndex;
          tail.startTime = e.time;
          tail.position = this.endPosition;
          tail.stackHeight = this.stackHeight;
          tail.classicSliderBehaviour = this.classicSliderBehaviour;
          this.addNested(tail);
          break;
        }

        case SliderEventType.Repeat: {
          const repeat = this.lastRepeat = new SliderRepeat(this);
          repeat.repeatIndex = e.spanIndex;
          repeat.startTime = this.startTime + (e.spanIndex + 1) * this.spanDuration;
          repeat.position = this.position.add(this.path.positionAt(e.pathProgress));
          repeat.stackHeight = this.stackHeight;
          repeat.pathProgress = e.pathProgress;
          this.addNested(repeat);
          break;
        }
      }
    }

    this.updateNestedSamples();
  }

  private updateNestedPositions(): void {
    this.endPositionCache = null;

    for (const nested of this.nestedHitObjects) {
      if (nested instanceof SliderHeadCircle)
        nested.position = this.position;
      else if (nested instanceof SliderTailCircle)
        nested.position = this.endPosition;
      else if (nested instanceof SliderRepeat)
        nested.position = this.position.add(this.path.positionAt(nested.pathProgress));
      else if (nested instanceof SliderTick)
        nested.position = this.position.add(this.path.positionAt(nested.pathProgress));
    }
  }

  protected updateNestedSamples(): void {
    populateNodeSamples(this);

    // TODO: remove this when guaranteed sort is present for samples (https://github.com/ppy/osu/issues/1933)
    const tickSample = (this.samples.find(s => s.name === HitSampleInfo.HIT_NORMAL) ?? this.samples[0])?.with({ name: 'slidertick' }) ?? null;

    for (const nested of this.nestedHitObjects) {
      if (nested instanceof SliderTick) {
        nested.samplesBindable.clear();

        if (tickSample !== null)
          nested.samplesBindable.add(tickSample);
      } else if (nested instanceof SliderRepeat)
        nested.samples = getNodeSamples(this, nested.repeatIndex + 1);
    }

    if (this.headCircle !== null)
      this.headCircle.samples = getNodeSamples(this, 0);

    // The samples should be attached to the slider tail, however this can only be done if LastTick is removed otherwise they would play earlier than they're intended to.
    // (see mapping logic in `CreateNestedHitObjects` above)
    //
    // For now, the samples are played by the slider itself at the correct end time.
    this.tailSamples = getNodeSamples(this, this.repeatCount + 1);
  }

  override createJudgement(): Judgement {
    return this.classicSliderBehaviour
      // Final combo is provided by the slider itself - see logic in `DrawableSlider.CheckForResult()`
      ? new OsuJudgement()
      // Final combo is provided by the tail circle - see `SliderTailCircle`
      : new OsuIgnoreJudgement();
  }

  protected override createHitWindows(): HitWindows | null {
    return HitWindows.Empty;
  }
}
