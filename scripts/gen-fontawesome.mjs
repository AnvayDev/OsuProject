// Generates src/framework/graphics/sprites/FontAwesome.ts from osu-framework's FontAwesome.cs (every Brands/Regular/Solid member, same names
// and codepoints). usage: node scripts/gen-fontawesome.mjs
import fs from 'node:fs';
import path from 'node:path';

const source = path.resolve('_reference/osu-framework/osu.Framework/Graphics/Sprites/FontAwesome.cs');
const out = path.resolve('src/framework/graphics/sprites/FontAwesome.ts');

const classes = new Map();
let current = null;

for (const line of fs.readFileSync(source, 'utf8').split('\n')) {
  const cls = /public static class (\w+)/.exec(line);
  if (cls && cls[1] !== 'FontAwesome') {
    classes.set(current = cls[1], []);
    continue;
  }

  // `public new static IconUsage Equals` hides object.Equals in C#.
  const member = /public (?:new )?static IconUsage (\w+) => Get\((0x[0-9a-fA-F]+)\);/.exec(line);
  if (member) {
    if (current === null) throw new Error(`Icon outside a nested class: ${line.trim()}`);
    classes.get(current).push([member[1], member[2].toLowerCase()]);
  }
}

const weights = [...classes.keys()];
if (weights.join() !== 'Brands,Regular,Solid') throw new Error(`Unexpected nested classes: ${weights}`);

const lines = [
  '// Ported from osu.Framework/Graphics/Sprites/FontAwesome.cs',
  '// Generated by scripts/gen-fontawesome.mjs: do not edit by hand. C# exposes each icon as a static property returning a new (immutable)',
  '// IconUsage; here each icon is one IconUsage instance. Nested static classes keep their C# member names (FontAwesome.Solid.Search).',
  '',
  "import { IconUsage } from './IconUsage';",
  '',
  "const get = (icon: number): IconUsage => new IconUsage(String.fromCharCode(icon), 'FontAwesome');",
  ...weights.map(w => `const ${w.toLowerCase()} = (icon: number): IconUsage => get(icon).with({ weight: '${w}' });`),
  '',
  'export const FontAwesome = {',
  '  get,',
];

for (const w of weights) {
  lines.push('', `  ${w}: {`, `    get: ${w.toLowerCase()},`);
  for (const [name, code] of classes.get(w))
    lines.push(`    ${name}: ${w.toLowerCase()}(${code}),`);
  lines.push('  },');
}

lines.push('};', '');

fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)}: ${weights.map(w => `${w} ${classes.get(w).length}`).join(', ')}`);
