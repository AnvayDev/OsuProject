// Generates src/game/graphics/OsuIcon.ts from osu's OsuIcon.cs (every public icon, the OsuIconMapping order and its texture descriptions).
// usage: node scripts/gen-osuicon.mjs
import fs from 'node:fs';
import path from 'node:path';

const source = path.resolve('_reference/osu/osu.Game/Graphics/OsuIcon.cs');
const out = path.resolve('src/game/graphics/OsuIcon.ts');

const text = fs.readFileSync(source, 'utf8');

const icons = [...text.matchAll(/public static IconUsage (\w+) => get\(OsuIconMapping\.(\w+)\);/g)].map(m => [m[1], m[2]]);

const enumBody = /private enum OsuIconMapping\s*\{([\s\S]*?)\n\s*\}/.exec(text)[1];
// Members are numbered like a C# enum: an explicit value resets the counter.
const mapping = [];
let next = 0;
for (const m of enumBody.matchAll(/\[Description\(@"([^"]+)"\)\]\s*(\w+)(?:\s*=\s*(\d+))?,/g)) {
  const value = m[3] !== undefined ? Number(m[3]) : next;
  mapping.push([m[2], m[1], value]);
  next = value + 1;
}
const ordinal = new Map(mapping.map(([name, , value]) => [name, value]));

for (const [, target] of icons)
  if (!ordinal.has(target)) throw new Error(`Unknown mapping ${target}`);

const lines = [
  '// Ported from osu.Game/Graphics/OsuIcon.cs',
  '// Generated by scripts/gen-osuicon.mjs: do not edit by hand. As in C#, an icon is the OsuIconMapping ordinal as a character of the "Icons"',
  '// font, and OsuIconStore resolves it to the texture named by the mapping\'s Description. The store loads a texture on its first async',
  '// lookup (FontStore.getAsync, awaited by SpriteIcon.load); synchronous lookups return what has been loaded.',
  '',
  "import { IconUsage } from '@fw/graphics/sprites/IconUsage';",
  "import type { Texture } from '@fw/graphics/textures/Texture';",
  "import type { TextureStore } from '@fw/graphics/textures/TextureStore';",
  "import type { ICharacterGlyph, ITexturedCharacterGlyph, ITexturedGlyphLookupStore, GlyphTexture } from '@fw/text/FontStore';",
  '',
  "const FONT_NAME = 'Icons';",
  '',
  'const get = (glyph: number): IconUsage => new IconUsage(String.fromCharCode(glyph), FONT_NAME);',
  '',
  '/** OsuIconMapping descriptions, by value. */',
  'const mappingDescriptions: Readonly<Record<number, string>> = {',
  ...mapping.map(([name, desc, value]) => `  ${value}: '${desc}', // ${name}`),
  '};',
  '',
  'export const OsuIcon = {',
  '  FONT_NAME,',
  '',
  ...icons.map(([name, target]) => `  ${name}: get(${ordinal.get(target)}),`),
  '};',
  '',
  'class Glyph implements ITexturedCharacterGlyph {',
  '  readonly xOffset = 0;',
  '  readonly yOffset = 0;',
  '  readonly xAdvance = 0;',
  '  readonly baseline = 0;',
  "  readonly character = '\\0';",
  '',
  '  getKerning(_lastGlyph: ICharacterGlyph): number {',
  "    throw new Error('Not implemented');",
  '  }',
  '',
  '  readonly texture: GlyphTexture;',
  '',
  '  constructor(private readonly source: Texture) {',
  '    this.texture = { pageUrl: source.url ?? \'\', pageWidth: source.width, pageHeight: source.height, x: 0, y: 0, width: source.width, height: source.height };',
  '  }',
  '',
  '  get width(): number {',
  '    return this.source.displayWidth;',
  '  }',
  '',
  '  get height(): number {',
  '    return this.source.displayHeight;',
  '  }',
  '}',
  '',
  'export class OsuIconStore implements ITexturedGlyphLookupStore {',
  '  private readonly loaded = new Map<string, Promise<Texture | null>>();',
  '  private readonly textureCache = new Map<string, Texture | null>();',
  '',
  '  constructor(private readonly textures: TextureStore) {}',
  '',
  '  get(fontName: string | null, character: string): ITexturedCharacterGlyph | null {',
  '    if (fontName === FONT_NAME) {',
  '      const texture = this.textureCache.get(character);',
  '      return texture ? new Glyph(texture) : null;',
  '    }',
  '',
  '    return null;',
  '  }',
  '',
  '  async getAsync(fontName: string | null, character: string): Promise<ITexturedCharacterGlyph | null> {',
  '    if (fontName !== FONT_NAME)',
  '      return null;',
  '',
  '    let task = this.loaded.get(character);',
  '',
  '    if (task === undefined) {',
  '      const description = mappingDescriptions[character.charCodeAt(0)];',
  '      task = description === undefined ? Promise.resolve(null) : this.textures.get(`${fontName}/${description}`);',
  '      this.loaded.set(character, task);',
  '      this.textureCache.set(character, await task);',
  '    } else',
  '      await task;',
  '',
  '    return this.get(fontName, character);',
  '  }',
  '}',
  '',
];

fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)}: ${icons.length} icons, ${mapping.length} mappings`);
